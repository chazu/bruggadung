#define HAVE_INCLUDE_LAB

/* This is a central include file to keep dependencies out of the library
   C files. It is usually included by .h files only.

   The advantage is that now .c and .h files become motile. They can
   be moved to other projects and don't need to be edited. Also less typing...

   Therefore it is important that this file is called "include.h" and
   not "lab-include.h" to keep the #include statements in the
   library code uniform.

   The C-compiler will pick up the nearest one.
*/

/* Include the header file automatically generated by mulle-sourcetree-to-c.
   Here the prefix is harmless and serves disambiguation. If you have no
   sourcetree, then you don't need it.
 */

#include "_lab-include.h"

// this is for WIN32: specify global non-inlined functions and variables
// like this (can not be declared inside functions!)
//
// .h:
// #include "include.h"
// LAB_GLOBAL char *   aGlobalString;
// LAB_GLOBAL void     aGlobalFunction( void);
//
// .c:
// #include "include-private.h"
// LAB_GLOBAL_VAR
// char *  aGlobalString = "VfL Bochum 1848";
// LAB_GLOBAL
// void   aGlobalFunction( void) {}
//
#ifndef LAB_GLOBAL
# ifdef LAB_BUILD
#  define LAB_GLOBAL       MULLE_C_GLOBAL
#  define LAB_GLOBAL_VAR   MULLE_C_GLOBAL
# else
#  if defined( LAB_INCLUDE_DYNAMIC) || (defined( MULLE_INCLUDE_DYNAMIC) && ! defined( LAB_INCLUDE_STATIC))
#   define LAB_GLOBAL      MULLE_C_GLOBAL
#  else
#   define LAB_GLOBAL      extern
#  endif
# endif
# define LAB_GLOBAL_VAR    MULLE_C_GLOBAL
#endif

